// Writes the lettering block for the app's panel artwork: assets/lettering.svg, an SVG fragment
// in panel units that src/ui/panel.rs includes. Run it after changing lettering.js:
//
//     node design/logo/export.js
const fs = require('fs');
const path = require('path');
const { block } = require('./lettering.js');

// the block on the black screen panel: left edge, top, width (panel units), and its ink
const b = block(85, 72, 200, '#a9acaf');
const out = path.join(__dirname, '..', '..', 'assets', 'lettering.svg');
fs.writeFileSync(out, `<!-- generated by design/logo/export.js from design/logo/lettering.js -->\n${b.svg}\n`);
console.log(`${path.relative(process.cwd(), out)}: ${fs.statSync(out).size} bytes`);
